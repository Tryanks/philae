#!/usr/bin/env python3
"""Generate a concrete Java subclass of an abstract framework class.

    scripts/gen-neutral-class.py <abstract class> <generated class> > File.java

Some framework APIs hand apps an object of an abstract class with a hundred abstract
methods (android.webkit.WebSettings, say), which a platform implementation must subclass.
This writes the subclass that makes such an object exist and behave like a plain record:
every setFoo(x) stores its argument and the matching getFoo()/isFoo()/foo() returns it;
other methods do nothing and return a neutral value (0, false, null). A hand-written
class then extends the generated one to give the properties their real defaults and to
implement the methods that have work to do.
"""
import re
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
jar = root / "third_party/robolectric/android-all-15.jar"
base, generated = sys.argv[1], sys.argv[2]
out = subprocess.run(["javap", "-p", "-cp", str(jar), base], capture_output=True, text=True, check=True).stdout

methods = []
for line in out.splitlines():
    m = re.match(r"\s+(public|protected) abstract (?:synchronized )?(\S.*?) (\w+)\((.*)\)(?: throws .*)?;", line)
    if m:
        access, ret, name, params = m.groups()
        fix = lambda t: t.replace("$", ".")
        params = [fix(p.strip()) for p in params.split(",")] if params.strip() else []
        methods.append((access, fix(ret), name, params))

def prop(name):
    """The property a method reads or writes, or None."""
    for prefix in ("set", "get", "is"):
        if name.startswith(prefix) and len(name) > len(prefix) and name[len(prefix)].isupper():
            return name[len(prefix):]
    return name[0].upper() + name[1:]

setters = {prop(n): p[0] for _, r, n, p in methods if n.startswith("set") and r == "void" and len(p) == 1}
boxes = {"boolean": "Boolean", "int": "Integer", "long": "Long", "float": "Float", "double": "Double",
         "byte": "Byte", "short": "Short", "char": "Character"}
neutral = {"boolean": "false", "char": "(char) 0", "void": None}

package, _, cls = generated.rpartition(".")
print(f"// Generated by scripts/gen-neutral-class.py from {base}. Do not edit.")
print(f"package {package};\n")
print(f"/** A {base.rpartition('.')[2]} that remembers what is set on it and does nothing else. */")
print(f"public class {cls} extends {base} {{")
print("    /** Property values by name (\"JavaScriptEnabled\"), as set or as given by a subclass. */")
print("    protected final java.util.Map<String, Object> mValues = new java.util.HashMap<>();\n")
for access, ret, name, params in methods:
    args = ", ".join(f"{t} a{i}" for i, t in enumerate(params))
    print("    @Override")
    print(f"    {access} synchronized {ret} {name}({args}) {{")
    p = prop(name)
    if name.startswith("set") and ret == "void" and len(params) == 1:
        print(f"        mValues.put(\"{p}\", a0);")
    elif ret != "void":
        default = neutral.get(ret, "0" if ret in boxes else "null")
        if not params and setters.get(p) == ret:
            boxed = boxes.get(ret, ret)
            print(f"        Object value = mValues.get(\"{p}\");")
            print(f"        return value != null ? ({boxed}) value : {default};")
        else:
            print(f"        return {default};")
    print("    }\n")
print("}")
