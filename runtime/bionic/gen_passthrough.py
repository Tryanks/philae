#!/usr/bin/env python3
"""Generate the bionic library's forwarding stubs from passthrough.txt.

Each stub is a single jump, so it works for any signature and leaves the caller's frame
exactly as the real function expects it (which setjmp requires).
"""
import sys

source, output = sys.argv[1], sys.argv[2]
lines = ["// Generated by gen_passthrough.py from passthrough.txt. Do not edit.", ".text"]
for line in open(source):
    for word in line.split("#")[0].split():
        name, _, target = word.partition("=")
        lines += [f".globl _bionic_{name}", ".p2align 2", f"_bionic_{name}:", f"    b _{target or name}"]
open(output, "w").write("\n".join(lines) + "\n")
